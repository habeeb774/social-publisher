export async function GET(request: NextRequest) {
  if (!process.env.CONTENT_SEED_TOKEN || request.nextUrl.searchParams.get("token") !== process.env.CONTENT_SEED_TOKEN) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }
  if (!process.env.DATABASE_URL) return NextResponse.json({ error: "DATABASE_UNAVAILABLE" }, { status: 503 });

  const db = neon(process.env.DATABASE_URL);
  const created: string[] = [];
  const skipped: string[] = [];

  for (const item of templates) {
    const existing = await db`SELECT id FROM quick_replies WHERE lower(name)=lower(${item.name}) LIMIT 1`;
    if (existing.length) {
      skipped.push(item.name);
      continue;
    }
    await db`INSERT INTO quick_replies(name,content,category,active,created_by)
      VALUES(${item.name},${item.content},${item.category},true,'system-defaults')`;
    created.push(item.name);
  }

  const [{ count }] = await db`SELECT count(*)::int AS count FROM quick_replies WHERE active`;
  return NextResponse.json({ ok: true, created, skipped, activeTemplates: Number(count) });
}
